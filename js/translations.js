// Helper: Localize Keyword List for an Emoji
function getLocalizedKeywords(item, lang) {
  if (!lang || lang === 'en') return item.keywords || [];
  if (!item.keywords) return [];

  return item.keywords.map(kw => {
    const cleanKw = kw.toLowerCase().trim();
    if (KEYWORD_TRANSLATIONS[cleanKw] && KEYWORD_TRANSLATIONS[cleanKw][lang]) {
      return KEYWORD_TRANSLATIONS[cleanKw][lang];
    }
    return kw;
  });
}
